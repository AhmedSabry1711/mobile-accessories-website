/** Resolve a dotted key with interpolation / function support (English only). */
export function translate(key, vars) {
  let value = resolve(en, key);
  if (value == null) return key;
  if (typeof value === 'function') return String(value(vars) ?? '');
  return String(value).replace(/\{(\w+)\}/g, (_, name) =>
    vars && vars[name] !== undefined && vars[name] !== null ? String(vars[name]) : `{${name}}`
  );
}

function resolve(dict, key) {
  return key.split('.').reduce((obj, part) => (obj == null ? undefined : obj[part]), dict);
}