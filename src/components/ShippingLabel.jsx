import { useEffect, useMemo, useState } from 'react';
import { createPortal } from 'react-dom';
import qrcode from 'qrcode-generator';
import { useUI } from '../context/UIContext.jsx';
import { money } from '../api/client.js';
import { COMPANY } from '../lib/company.js';
import { IconClose, IconPrinter } from './icons.jsx';

/**
 * Printable shipping label — 70 × 100 mm (7 × 10 cm), the size used by courier
 * label printers in Egypt.
 *
 * The label is rendered into a portal on <body> so the printed page contains
 * nothing but the label: `@media print` hides every other body child and an
 * injected `@page` rule pins the paper size. It carries a real QR code that
 * links to the order confirmation page (`confirmUrl` is generated by the admin
 * API from a per-order signed code, never from the order number alone).
 *
 * Every value comes from the live order / store settings — nothing is hardcoded.
 * Styles live in src/styles.css under the `.sl-*` / `.label-*` blocks.
 */
const QR_ERROR_LEVEL = 'M';

export default function ShippingLabel({ order, settings, confirmUrl, onClose }) {
  const { t, lang, locale } = useUI();
  const isRtl = lang === 'ar';

  const symbol = settings?.currency?.symbol || '';

  const items = useMemo(() => order?.items || [], [order]);
  const pieces = useMemo(
    () => items.reduce((sum, item) => sum + Number(item.qty || 0), 0),
    [items],
  );

  const orderDate = order?.createdAt
    ? new Date(order.createdAt).toLocaleDateString(locale, {
        day: '2-digit',
        month: '2-digit',
        year: 'numeric',
      })
    : '';

  const [qrSvg, setQrSvg] = useState('');
  useEffect(() => {
    if (!confirmUrl) {
      setQrSvg('');
      return;
    }
    try {
      const qr = qrcode(0, QR_ERROR_LEVEL);
      qr.addData(confirmUrl);
      qr.make();
      // margin: 0 — the quiet zone is provided by the white .sl-qr padding.
      setQrSvg(qr.createSvgTag({ cellSize: 2, margin: 0, scalable: true }));
    } catch {
      setQrSvg('');
    }
  }, [confirmUrl]);

  useEffect(() => {
    if (!order) return undefined;

    // Pin the paper size while the label is open; the browser would otherwise
    // fall back to A4 and shrink the label into a corner.
    const pageStyle = document.createElement('style');
    pageStyle.id = 'shipping-label-page';
    pageStyle.textContent = '@page { size: 70mm 100mm; margin: 0; }';
    document.head.appendChild(pageStyle);

    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = 'hidden';

    const onKeyDown = (event) => {
      if (event.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onKeyDown);

    return () => {
      pageStyle.remove();
      document.body.style.overflow = previousOverflow;
      window.removeEventListener('keydown', onKeyDown);
    };
  }, [order, onClose]);

  if (!order) return null;

  const status = order.status || 'pending';
  const statusLabel = t(`admin.status.${status}`) || status;

  // The courier collects `order.total`, so the label spells out how that number
  // was reached whenever a coupon changed it.
  const subtotal = Number(order.subtotal || 0);
  const discount = Number(order.discount || 0);
  const shippingFee = Number(order.shippingFee || 0);

  return createPortal(
    <div
      className="label-portal"
      role="dialog"
      aria-modal="true"
      aria-label={t('admin.orders.label.shipping')}
    >
      <div className="label-toolbar">
        <button type="button" className="btn btn-primary btn-sm" onClick={() => window.print()}>
          <IconPrinter size={16} />
          {t('admin.orders.label.print')}
        </button>
        <button type="button" className="btn btn-outline btn-sm" onClick={onClose}>
          <IconClose size={16} />
          {t('admin.orders.label.close')}
        </button>
      </div>

      <article className="shipping-label" dir={isRtl ? 'rtl' : 'ltr'} lang={isRtl ? 'ar' : 'en'}>
        <div className="sl-topbar" />

        {/* ---------------------------------------------------------- header */}
        <header className="sl-head">
          <div className="sl-brand">
            <img className="sl-logo" src="/logo.png" alt={COMPANY.name} />
            <div className="sl-brand-text">
              <strong className="sl-brand-name">{COMPANY.name}</strong>
              <span className="sl-brand-tag">{COMPANY.tagline[isRtl ? 'ar' : 'en']}</span>
            </div>
          </div>

          <div className="sl-head-side">
            <span className="sl-doc-title">{t('admin.orders.label.shipping')}</span>
            <strong className="sl-order-no sl-ltr">{order.orderNumber}</strong>
            <div className="sl-meta">
              <span>{orderDate}</span>
              <span className={`sl-status sl-status-${status}`}>{statusLabel}</span>
            </div>
          </div>
        </header>

        {/* ------------------------------------------------------- recipient */}
        <section className="sl-section sl-recipient">
          <h2 className="sl-section-title">{t('admin.orders.label.recipient')}</h2>
          <div className="sl-recipient-top">
            <strong className="sl-recipient-name">{order.customer?.name || ''}</strong>
            {order.customer?.phone && (
              <span className="sl-phone sl-ltr" dir="ltr">
                {order.customer.phone}
              </span>
            )}
          </div>
          <p className="sl-address">
            <span className="sl-address-label">{t('admin.orders.label.address')}:</span>{' '}
            <span className="sl-address-text">{order.customer?.address || ''}</span>
          </p>
          {order.customer?.landmark && (
            <p className="sl-landmark">
              <span className="sl-landmark-tag">{t('admin.orders.label.landmark')}</span>{' '}
              {order.customer.landmark}
            </p>
          )}
        </section>

        {/* -------------------------------------------------------- contents */}
        <section className="sl-section sl-contents">
          <h2 className="sl-section-title">
            {t('admin.orders.label.contents')}
            <span className="sl-pieces">{t('admin.orders.label.pieces', { n: pieces })}</span>
          </h2>
          {items.length ? (
            <ul className="sl-items">
              {items.map((item, index) => {
                const variant = [item.model, item.color].filter(Boolean).join(' · ');
                return (
                  <li className="sl-item" key={`${item.name || 'item'}-${index}`}>
                    <span className="sl-item-name">
                      {item.name || ''}
                      {variant && <span className="sl-item-variant"> — {variant}</span>}
                    </span>
                    <span className="sl-item-qty sl-ltr" dir="ltr">
                      ×{item.qty}
                    </span>
                  </li>
                );
              })}
            </ul>
          ) : (
            <p className="sl-empty">—</p>
          )}
        </section>

        {/* ------------------------------------------------- payment + QR code */}
        <section className="sl-section sl-bottom">
          <div className="sl-pay">
            <div className="sl-pay-label">{t('admin.orders.label.cod')}</div>
            <div className="sl-pay-total">
              <span className="sl-ltr" dir="ltr">
                {money(order.total)}
              </span>
              {symbol && <span className="sl-currency">{symbol}</span>}
            </div>

            {discount > 0 && (
              <div className="sl-pay-row">
                <span>{t('admin.orders.label.subtotal')}</span>
                <span className="sl-ltr" dir="ltr">
                  {money(subtotal)} {symbol}
                </span>
              </div>
            )}

            {discount > 0 && (
              <div className="sl-pay-row sl-row-discount">
                <span>
                  {t('admin.orders.label.discount')}
                  {order.couponCode ? ` (${order.couponCode})` : ''}
                </span>
                <span className="sl-ltr" dir="ltr">
                  −{money(discount)} {symbol}
                </span>
              </div>
            )}

            <div className="sl-pay-row">
              <span>{t('admin.orders.label.shippingFee')}</span>
              <span className="sl-ltr" dir="ltr">
                {shippingFee > 0
                  ? `${money(shippingFee)} ${symbol}`
                  : t('admin.orders.label.free')}
              </span>
            </div>

            <div className="sl-pay-row">
              <span>{t('admin.orders.label.paymentMethod')}</span>
              <span>{t('admin.orders.label.codMethod')}</span>
            </div>
          </div>

          <div className="sl-qr-wrap">
            {qrSvg ? (
              <div
                className="sl-qr"
                // The SVG is generated locally by qrcode-generator from a URL.
                dangerouslySetInnerHTML={{ __html: qrSvg }}
              />
            ) : (
              <div className="sl-qr sl-qr-empty">{t('admin.orders.label.qr_unavailable')}</div>
            )}
            <div className="sl-qr-note">{t('admin.orders.label.scan')}</div>
          </div>
        </section>

        {/* ----------------------------------------------------------- footer */}
        <footer className="sl-foot">
          <div className="sl-foot-row">
            <span className="sl-foot-item">
              {t('admin.orders.label.support')}:{' '}
              <span className="sl-ltr" dir="ltr">
                {COMPANY.phone}
              </span>
            </span>
            <span className="sl-foot-item sl-ltr" dir="ltr">
              {COMPANY.website}
            </span>
            <span className="sl-foot-item">{COMPANY.city[isRtl ? 'ar' : 'en']}</span>
          </div>
          <div className="sl-foot-brand">{COMPANY.name}</div>
        </footer>
      </article>
    </div>,
    document.body,
  );
}
